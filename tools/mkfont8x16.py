#!/usr/bin/env python3
"""
Rasterize printable ASCII into an 8x16 1-bit bitmap font header (font8x16.h).
Linux alternative to mkfont8x16.swift using Pillow.
"""
from PIL import Image, ImageDraw, ImageFont
import sys

FONT_PATHS = [
    "/usr/share/fonts/truetype/noto/NotoMono-Regular.ttf",
    "/usr/share/fonts/truetype/freefont/FreeMonoBold.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
]

font_path = None
for p in FONT_PATHS:
    try:
        open(p).close()
        font_path = p
        break
    except OSError:
        continue

if not font_path:
    # Fallback default
    font = ImageFont.load_default()
else:
    font = ImageFont.truetype(font_path, 13)

W, H = 8, 16
out = []
out.append("/* Generated by tools/mkfont8x16.py: ASCII 0x20-0x7e, 8x16 bitmap font, MSB = left. */")
out.append("static const unsigned char font8x16[95][16] = {")

for code in range(0x20, 0x7f):
    im = Image.new("1", (W, H), 0)
    draw = ImageDraw.Draw(im)
    ch = chr(code)
    # Center glyph
    draw.text((0, 0), ch, font=font, fill=1)
    rows = []
    for y in range(H):
        b = 0
        for x in range(W):
            if im.getpixel((x, y)):
                b |= (0x80 >> x)
        rows.append(f"0x{b:02x}")
    desc = "backslash" if ch == "\\" else ("asterisk" if ch == "*" else ch)
    out.append(f"    {{ {', '.join(rows)} }}, /* {desc} */")

out.append("};")
sys.stdout.write("\n".join(out) + "\n")
